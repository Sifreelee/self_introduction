const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const { orderPhotos } = require('../js/photo-order.js');
const names = ['午门 其十', '别的照片', '午门 其二', '午门 十二', '午门 其一', '午门 十一'];
const photos = names.map((name, i) => ({src: `assets/images/${name}.jpg`, title: name, custom: i}));
const ordered = orderPhotos(photos);
assert.deepStrictEqual(ordered.map(p => p.title), [4, 2, 0, 5, 3, 1].map(i => names[i]));
assert.strictEqual(ordered[0], photos[4]);
assert.deepStrictEqual(photos.map(p => p.title), names);
assert.deepStrictEqual(orderPhotos(ordered), ordered);
const numbers = ['photo10', 'photo2', 'photo1'].map(name => ({src: `${name}.jpg`}));
assert.deepStrictEqual(orderPhotos(numbers).map(p => p.src), ['photo1.jpg', 'photo2.jpg', 'photo10.jpg']);
const data = fs.readFileSync(path.join(__dirname, '../js/data.js'), 'utf8');
const context = {};
vm.createContext(context);
vm.runInContext(data + '\nglobalThis.albums = SITE_DATA.photos;', context);
const main = fs.readFileSync(path.join(__dirname, '../js/main.js'), 'utf8');
const init = main.slice(main.indexOf('(SITE_DATA.photos || []).forEach'), main.indexOf('/* ─────────── 内置图标集'));
context.orderPhotos = orderPhotos;
const cities = context.albums.map(a => a.city);
const counts = context.albums.map(a => a.photos.length);
vm.runInContext(init, context);
assert.deepStrictEqual(context.albums.map(a => a.city), cities);
assert.deepStrictEqual(context.albums.map(a => a.photos.length), counts);
assert(context.albums.find(a => a.city === '北京 故宫'));
console.log('Photo order: ordinals, regrouping, numeric names, metadata and real website initialization passed.');
